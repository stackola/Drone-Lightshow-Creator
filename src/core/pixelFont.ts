/** One line of text as a dot bitmap, 5 (3×5 font) or 7 (5×7 font) dots tall, one blank column between letters. */
export function dotTextBitmap(text: string, height: 5 | 7): { w: number; h: number; on: Uint8Array } {
  const font = height === 5 ? S : G
  const gw = height === 5 ? 3 : 5
  const chars = [...text.toUpperCase()]
  const w = Math.max(1, chars.length * (gw + 1) - 1)
  const on = new Uint8Array(w * height)
  chars.forEach((ch, ci) => {
    const g = font[ch]
    if (!g) return
    const rows = g.split('|')
    for (let r = 0; r < height; r++) for (let c = 0; c < gw; c++) if (rows[r]![c] === '#') on[r * w + ci * (gw + 1) + c] = 1
  })
  return { w, h: height, on }
}
