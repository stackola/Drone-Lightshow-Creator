/** Rasterise text (multi-line with \n) into a mask; each font pixel becomes `scale`² mask pixels. */
export function pixelTextMask(text: string, scale = 6): Mask {
  const lines = text.toUpperCase().split('\n')
  const glyphW = 5, glyphH = 7, gap = 1, lineGap = 3
  const widths = lines.map((l) => Math.max(0, [...l].length * (glyphW + gap) - gap))
  const W = Math.max(1, ...widths)
  const H = lines.length * glyphH + (lines.length - 1) * lineGap
  const on = new Uint8Array(W * H)
  lines.forEach((line, li) => {
    const x0 = Math.floor((W - widths[li]!) / 2)
    const y0 = li * (glyphH + lineGap)
    ;[...line].forEach((ch, ci) => {
      const g = G[ch]
      if (!g) return
      const rows = g.split('|')
      for (let r = 0; r < glyphH; r++)
        for (let c = 0; c < glyphW; c++) if (rows[r]![c] === '#') on[(y0 + r) * W + x0 + ci * (glyphW + gap) + c] = 1
    })
  })
  return encodeMask(W * scale, H * scale, (x, y) => on[Math.floor(y / scale) * W + Math.floor(x / scale)] === 1)
}
